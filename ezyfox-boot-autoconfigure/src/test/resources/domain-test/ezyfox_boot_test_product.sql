CREATE TABLE IF NOT EXISTS `ecommerce_products` (
    `id` bigint unsigned NOT NULL AUTO_INCREMENT,
    `product_name` varchar(300) COLLATE utf8mb4_unicode_520_ci NOT NULL,
    `product_code` varchar(120) COLLATE utf8mb4_unicode_520_ci NOT NULL,
    `secondary_code` varchar(120) COLLATE utf8mb4_unicode_520_ci,
    `icon_image_id` bigint unsigned NOT NULL DEFAULT 0,
    `banner_image_id` bigint unsigned NOT NULL DEFAULT 0,
    `shop_id` bigint unsigned NOT NULL DEFAULT 0,
    `display_order` bigint NOT NULL DEFAULT 0,
    `amount` bigint NOT NULL DEFAULT 0,
    `sold_amount` bigint NOT NULL DEFAULT 0,
    `product_type` varchar(50) COLLATE utf8mb4_unicode_520_ci NOT NULL DEFAULT 'SINGLE',
    `parent_id` bigint unsigned NOT NULL DEFAULT 0,
    `creator_admin_id` bigint unsigned NOT NULL DEFAULT 0,
    `creator_user_id` bigint unsigned NOT NULL DEFAULT 0,
    `status` varchar(50) COLLATE utf8mb4_unicode_520_ci NOT NULL,
    `created_at` datetime NOT NULL,
    `updated_at` datetime NOT NULL,
    PRIMARY KEY (`id`),
    INDEX `index_product_name` (`product_name`),
    INDEX `index_product_code` (`product_code`),
    INDEX `index_secondary_code` (`secondary_code`),
    INDEX `index_amount` (`amount`),
    INDEX `index_sold_amount` (`sold_amount`),
    INDEX `index_product_type` (`product_type`),
    INDEX `index_parent_id_id` (`parent_id`, `id`),
    INDEX `index_creator_admin_id` (`creator_admin_id`),
    INDEX `index_creator_user_id` (`creator_user_id`),
    INDEX `index_created_at` (`created_at`),
    INDEX `index_updated_at` (`updated_at`),
    INDEX `index_status_updated_at_id` (`status`, `updated_at`, `id`),
    INDEX `index_shop_pagination` (`shop_id`, `product_type`, `status`, `display_order`, `id`),
    INDEX `index_shop_type_status_id` (`shop_id`, `product_type`, `status`, `id`),
    INDEX `index_shop_type_status_sold_amount_id` (`shop_id`, `product_type`, `status`, `sold_amount`, `id`)
) ENGINE=InnoDB AUTO_INCREMENT=1 DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_520_ci;

CREATE TABLE IF NOT EXISTS `ecommerce_product_books` (
    `product_id` bigint unsigned NOT NULL,
    `author` varchar(120) COLLATE utf8mb4_unicode_520_ci NOT NULL,
    `author_user_id` bigint unsigned NOT NULL DEFAULT 0,
    `author_url` varchar(300) COLLATE utf8mb4_unicode_520_ci,
    `book_type` varchar(50) COLLATE utf8mb4_unicode_520_ci NOT NULL,
    `pages` int unsigned NOT NULL,
    `cover_type` varchar(50) COLLATE utf8mb4_unicode_520_ci NOT NULL,
    `affiliate` varchar(300) COLLATE utf8mb4_unicode_520_ci,
    `preview_link` varchar(300) COLLATE utf8mb4_unicode_520_ci,
    `distribution_company` varchar(250) COLLATE utf8mb4_unicode_520_ci,
    `distribution_company_id` bigint unsigned NOT NULL DEFAULT 0,
    `publisher` varchar(120) COLLATE utf8mb4_unicode_520_ci,
    `publisher_id` bigint unsigned NOT NULL DEFAULT 0,
    `number_of_authors` int unsigned NOT NULL DEFAULT 0,
    `released_at` datetime,
    PRIMARY KEY (`product_id`),
    INDEX `index_author_user_id` (`author_user_id`),
    INDEX `index_book_type` (`book_type`),
    INDEX `index_cover_type` (`cover_type`),
    INDEX `index_publisher_id` (`publisher_id`),
    INDEX `index_distribution_company_id` (`distribution_company_id`),
    INDEX `index_released_at` (`released_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_520_ci;
